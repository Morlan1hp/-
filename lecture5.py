def StringMatching(pattern, text):
    # pattern is a character array
    # text is a character array
    m = len(pattern)
    n = len(text)
    for i in range(0, n - m + 1): # i indexes text
        j = 0
        
        while j < m and pattern[j] == text[i + j]:  # j indexes pattern
            j = j + 1
            
        if j == m:
            
            return i
    
    return -1


