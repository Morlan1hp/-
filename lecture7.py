# complexity O(|V|)
def has_edge(G,u,v):
    for w in G[u]:
        if w == v:
            return True
    return False

# complexity O(|path|*|V|)
def is_path(G,path):
    # G is a graph (adjacency list)
    if len(path) > 1:
        s = path[0] # s indexes nodes of G
        d = path[1] # d indexes nodes of G
        
        return has_edge(G,s,d) and is_path(G,path[1:])
    else:
        return True


