"""# Recursive Factorial"""

# the recursive version below is approximately equivalent to this iterative version
def FAC2(n):
    result = 1
    while n > 0:
        result = result * n
        n = n - 1
    return result

def FAC(n):
    
    if n == 0:
        return 1
    # this is equivalent to return FAC(n - 1) * n but allows us
    # to insert a snapshot call after the recursive call returns
    r = FAC(n-1)
    
    return r * n


FAC(5)

"""# Recursive Fibonacci"""

def Fib(n):
    
    if n == 0:
        return 1
    if n == 1:
        return 1
    # equivalent to     return Fib(n - 1) + Fib(n - 2)
    a = Fib(n - 1)
    
    b = Fib(n - 2)
    
    return a + b


print(Fib(4))

"""# Linear Fibonacci (Iterative)
Here is a version of Fibonacci that has linear complexity in n (since the loop now runs n times)
"""

def Fib3(n):
    a = 1
    b = 0
    while n > 0:
        
        a = a + b
        b = a - b
        n = n - 1
    
    return a


Fib3(4)

"""# Linear Fibonacci (Recursive)
We can phrase the linear version using recursion.
"""

def Fib2(n, a=1, b=0):
    
    if n == 0:
        return a
    # equivalent to   return Fib2(n - 1, a + b, a)
    # (Not examinable: note how Python doesn't do tail call optimisation.
    #  To see, try replacing the three lines below with the commented-out
    #  return statement above. Notice how the stack grows on each recursive
    #  call. Tail-call optimisation avoids growing the stack in this way.)
    r = Fib2(n - 1, a + b, a)
    
    return r


print(Fib2(4))

