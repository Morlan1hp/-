"""# Selection Sort"""

# Function to swap between two array elements
def swap(A,i,j):
    temp = A[i]
    A[i] = A[j]
    A[j] = temp

# Sorting Array in ascending order using selection sort
def selection_sort(A):
    # A is an array
    for i in range(0,len(A)):        # i indexes A
        
        min = i                      # min indexes A
        
        for j in range(i+1,len(A)):  # j indexes A
            
            if A[j] < A[min]:
                min = j
                
        
        swap(A,i,min)
        
    return A


