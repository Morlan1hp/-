"""# Factorial"""

# The function finds the factorial of a number 'n' recursively
def fact(n):
    
    if n == 0:
        return 1
    else:
        # the following is equivalent to doing return n*fact(n-1)
        # but we write it this way so we can insert a 
        # call after the recursive call to fact(n-1) has finished
        r = fact(n-1)
        
        return n*r


n = 5
res = fact(n)

"""# Binary Search"""

import math

# The binsearch function finds the key in the Array and returns corresponding index,
# returns -1 if not found
def binsearch(A,lo,hi,key):
    # A is an array
    # lo indexes A
    # hi indexes A
    # mid indexes A
    if lo > hi:
        return -1
    mid = lo + math.floor((hi-lo)/2)
    
    if A[mid] == key:
        return mid
    else:
        if A[mid] > key:
            return binsearch(A,lo,mid-1,key)
        else:
            return binsearch(A,mid+1,hi,key)


